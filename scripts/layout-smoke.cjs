const {_electron:electron}=require('playwright');
const assert=require('node:assert/strict');
const {resolve}=require('node:path');
const {mkdtempSync,mkdirSync}=require('node:fs');
mkdirSync('evidence/layout',{recursive:true});
const data=mkdtempSync(resolve('evidence/layout/data-'));
let app;
const errors=[];
async function launch(){app=await electron.launch({args:[resolve('scripts/demo-harness.cjs')],chromiumSandbox:true,env:{...process.env,COUNCIL_TEST_DATA:data}});const page=await app.firstWindow();page.on('pageerror',e=>errors.push(e.message));await page.getByRole('heading',{name:'产品灵感讨论室'}).waitFor();return page}
(async()=>{
 let page=await launch();
 await page.getByText('一个问题，多种可能。',{exact:true}).waitFor();
 await page.screenshot({path:'evidence/layout/expanded.png'});
 const width=async()=>(await page.locator('.workspace').boundingBox()).width;
 const original=await width();
 await page.getByRole('textbox',{name:'消息内容'}).fill('布局切换保留草稿');
 await page.getByRole('button',{name:'收起群聊侧栏',exact:true}).click();
 assert.ok(await width()>original+150);
 await page.getByRole('button',{name:'收起成员侧栏',exact:true}).click();
 assert.ok(await width()>original+400);
 assert.equal(await page.getByRole('textbox',{name:'消息内容'}).inputValue(),'布局切换保留草稿');
 await page.screenshot({path:'evidence/layout/focused.png'});
 await app.close();app=null;page=await launch();
 assert.equal(await page.getByRole('button',{name:'展开群聊侧栏'}).getAttribute('aria-expanded'),'false');
 assert.equal(await page.getByRole('button',{name:'展开成员侧栏'}).getAttribute('aria-expanded'),'false');
 await page.getByRole('button',{name:'退出专注模式',exact:true}).click();
 assert.equal(await width(),original);
 await page.getByRole('button',{name:'收起群聊侧栏',exact:true}).click();
 await page.getByRole('button',{name:'专注模式',exact:true}).click();
 await page.getByRole('button',{name:'退出专注模式',exact:true}).click();
 assert.equal(await page.getByRole('button',{name:'展开群聊侧栏'}).count(),1);
 assert.equal(await page.getByRole('button',{name:'收起成员侧栏'}).count(),1);
 await page.getByRole('button',{name:'展开群聊侧栏'}).click();
 await page.evaluate(async()=>{const s=await window.council.getState();await window.council.saveSettings({...s.settings,theme:'dark'})});
 await page.waitForFunction(()=>document.documentElement.dataset.theme==='dark');
 await page.getByRole('button',{name:'发起新群聊',exact:true}).click();
 await page.getByPlaceholder('例如：产品灵感实验室').waitFor();
 await page.screenshot({path:'evidence/layout/dark-modal.png'});
 await page.getByRole('button',{name:'取消',exact:true}).click();
 await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].setSize(800,650));
 await page.screenshot({path:'evidence/layout/compact.png'});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 await page.getByRole('button',{name:'专注模式',exact:true}).click();
 await page.screenshot({path:'evidence/layout/compact-focused.png'});
 assert.ok(await width()>=730);
 assert.deepEqual(errors,[]);
 console.log('PASS: independent collapse, preserved draft, restart persistence, focus restoration, dark modal, 800px window; no renderer errors');
})().catch(e=>{console.error(e);process.exitCode=1}).finally(async()=>{await app?.close()});
